"""Install the job-handoff hotkey as a Hammerspoon module (macOS).

Writes ~/.hammerspoon/autohunter.lua and makes sure ~/.hammerspoon/init.lua loads it, without
touching anything else the user has there. The key comes from settings ("hotkey", e.g. "⌥Space").
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
from pathlib import Path

LUA = r'''-- AutoHunter job handoff (generated by `main.py hotkey install`; edits get overwritten)
local ROOT = "__ROOT__"
local UV = "__UV__"
local MODS, KEY = __MODS__, "__KEY__"

local function findWebArea(el, depth)
  if not el or depth > 25 then return nil end
  if el:attributeValue("AXRole") == "AXWebArea" then return el end
  for _, child in ipairs(el:attributeValue("AXChildren") or {}) do
    local found = findWebArea(child, depth + 1)
    if found then return found end
  end
end

local function currentTab()
  local app = hs.application.frontmostApplication()
  if not app or app:name() ~= "Google Chrome" then return nil end
  local win = hs.axuielement.applicationElement(app):attributeValue("AXFocusedWindow")
  local web = findWebArea(win, 0)
  if not web then return nil end
  local url = web:attributeValue("AXURL")
  if type(url) == "table" then url = url.url end
  return url, web:attributeValue("AXTitle") or ""
end

autohunterHotkey = hs.hotkey.bind(MODS, KEY, function()
  local url, title = currentTab()
  if not url then
    hs.alert.show("AutoHunter：在 Chrome 的岗位页面上按")
    return
  end
  hs.alert.show("AutoHunter：收到，检查中…")
  local t = hs.task.new(UV, function(code, out, err)
    local f = io.open(ROOT .. "/me/output/hotkey.log", "a")
    if f then
      f:write(os.date("%Y-%m-%d %H:%M:%S"), "  exit=", tostring(code), "  ", url, "\n", out or "", err or "", "\n")
      f:close()
    end
    if code ~= 0 then hs.alert.show("AutoHunter 出错了，看 me/output/hotkey.log") end
  end, {"run", "main.py", "handoff", url, "--title", title})
  t:setWorkingDirectory(ROOT)
  local env = hs.task.new("/usr/bin/true", nil):environment()
  env["PATH"] = "/opt/homebrew/bin:/usr/local/bin:" .. os.getenv("HOME") .. "/.local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
  env["HOME"] = os.getenv("HOME")
  t:setEnvironment(env)
  t:start()
end)
'''

SYMBOLS = {"⌃": "ctrl", "⌥": "alt", "⇧": "shift", "⌘": "cmd"}


def parse(hotkey: str) -> tuple[list[str], str]:
    mods = [SYMBOLS[c] for c in hotkey if c in SYMBOLS]
    key = re.sub(r"[⌃⌥⇧⌘]", "", hotkey).strip().lower() or "space"
    return mods or ["alt"], key


def install(me: Path, main_py: Path) -> str:
    cfg = json.loads((me / "config.json").read_text(encoding="utf-8")).get("apply", {})
    mods, key = parse(cfg.get("hotkey") or "⌥Space")
    uv = shutil.which("uv") or "/opt/homebrew/bin/uv"
    lua = (LUA.replace("__ROOT__", str(main_py.parent)).replace("__UV__", uv)
              .replace("__MODS__", "{" + ", ".join(f'"{m}"' for m in mods) + "}").replace("__KEY__", key))
    hs = Path.home() / ".hammerspoon"
    hs.mkdir(exist_ok=True)
    (hs / "autohunter.lua").write_text(lua, encoding="utf-8")
    init = hs / "init.lua"
    text = init.read_text(encoding="utf-8") if init.exists() else ""
    if 'require("autohunter")' not in text:
        text = text.rstrip() + '\nrequire("hs.ipc")\nrequire("autohunter")\n'
        init.write_text(text.lstrip(), encoding="utf-8")
    subprocess.run(["killall", "Hammerspoon"], capture_output=True)
    subprocess.run(["open", "-g", "-a", "Hammerspoon"], capture_output=True)
    return f"快捷键 {cfg.get('hotkey') or '⌥Space'} 已装好（{'+'.join(mods)}+{key}）。在 Chrome 的岗位页面上按它。"
